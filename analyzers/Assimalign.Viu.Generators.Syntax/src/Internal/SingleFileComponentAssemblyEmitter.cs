using System;
using System.Collections.Immutable;
using System.Text;

using Assimalign.Viu.Compiler.SingleFileComponent;

namespace Assimalign.Viu.Generators.Syntax;

/// <summary>
/// Emits the one-per-consumer-assembly registration catalog and tier-three render glue. The glue
/// calls only the adopted public runtime surface and BCL contracts; no state or type identity is
/// copied across assemblies. Specified by <c>[SFC-CG-2]</c> through <c>[SFC-CG-4]</c>.
/// </summary>
/// <remarks>
/// The catalog is this emitter's own; the glue text is
/// <see cref="SingleFileComponentRenderGlue.Source"/>, shared with the language service so the
/// editor's compilation contains the same glue this build writes.
/// </remarks>
internal static class SingleFileComponentAssemblyEmitter
{
    /// <summary>The deterministic hint name for the assembly-wide generated source.</summary>
    public const string HintName = "Viu.SingleFileComponentAssembly.g.cs";

    /// <summary>Emits the assembly catalog and internal glue.</summary>
    /// <param name="rootNamespace">The consumer's root namespace, or <see langword="null"/>.</param>
    /// <param name="registrations">The generated component registrations in the compilation.</param>
    /// <returns>The complete assembly-wide generated source.</returns>
    public static string Emit(
        string? rootNamespace,
        ImmutableArray<GeneratedComponentRegistration> registrations,
        string assemblyIdentity = "",
        ImmutableArray<GeneratedCatalogReference> references = default,
        bool autoRegister = true)
    {
        var ordered = new GeneratedComponentRegistration[registrations.Length];
        registrations.CopyTo(ordered);
        Array.Sort(ordered, static (left, right) =>
            StringComparer.Ordinal.Compare(left.FilePath, right.FilePath));

        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n#nullable enable\n\n");
        string catalogPrefix = string.IsNullOrEmpty(rootNamespace) ? "global::" : "global::" + rootNamespace + ".";
        string catalogSuffix = CatalogSuffix(assemblyIdentity);
        string componentCatalogName = "GeneratedViuComponents_" + catalogSuffix;
        string serverCatalogName = "GeneratedViuServerRenders_" + catalogSuffix;
        builder.Append("[assembly: global::Assimalign.Viu.Components.ComponentCatalog(typeof(")
            .Append(catalogPrefix).Append(componentCatalogName).Append("))]\n");
        bool ownsServerRenders = Array.Exists(ordered, static registration => registration.HasServerRender);
        if (ownsServerRenders)
        {
            builder.Append("[assembly: global::Assimalign.Viu.ServerRenderer.ServerRenderCatalog(typeof(")
                .Append(catalogPrefix).Append(serverCatalogName).Append("))]\n");
        }
        var hasNamespace = !string.IsNullOrEmpty(rootNamespace);
        if (hasNamespace)
        {
            builder.Append("namespace ").Append(rootNamespace).Append("\n{\n");
        }

        var indent = hasNamespace ? "    " : string.Empty;
        builder.Append(indent)
            .Append("/// <summary>Registers every compiled single-file component in this assembly.</summary>\n")
            .Append(indent)
            .Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Assimalign.Viu.Generators.Syntax\", \"1.0.0.0\")]\n")
            .Append(indent)
            .Append("public static class ").Append(componentCatalogName).Append("\n")
            .Append(indent)
            .Append("{\n")
            .Append(indent)
            .Append("    /// <summary>Adds every generated registration to the supplied factory.</summary>\n")
            .Append(indent)
            .Append("    /// <param name=\"factory\">The application-owned component factory.</param>\n")
            .Append(indent)
            .Append("    public static void Register(global::Assimalign.Viu.Components.ComponentFactory factory)\n")
            .Append(indent)
            .Append("    {\n")
            .Append(indent)
            .Append("        global::System.ArgumentNullException.ThrowIfNull(factory);\n");

        foreach (var registration in ordered)
        {
            builder.Append(indent).Append("        factory.Register(")
                .Append(QualifiedTypeName(registration))
                .Append(".__ViuRegistration);\n");
        }

        builder.Append(indent).Append("    }\n")
            .Append(indent).Append("}\n");

        bool hasServerRenders = false;
        foreach (var registration in ordered)
        {
            if (registration.HasServerRender)
            {
                hasServerRenders = true;
                break;
            }
        }

        if (hasServerRenders)
        {
            builder.Append('\n')
                .Append(indent)
                .Append("/// <summary>Registers every compiler-produced server render in this assembly.</summary>\n")
                .Append(indent)
                .Append("[global::System.CodeDom.Compiler.GeneratedCode(\"Assimalign.Viu.Generators.Syntax\", \"1.0.0.0\")]\n")
                .Append(indent)
                .Append("public static class ").Append(serverCatalogName).Append("\n")
                .Append(indent)
                .Append("{\n")
                .Append(indent)
                .Append("    /// <summary>Adds every generated server registration to the supplied registry.</summary>\n")
                .Append(indent)
                .Append("    /// <param name=\"registry\">The server-host-owned render registry.</param>\n")
                .Append(indent)
                .Append("    public static void Register(global::Assimalign.Viu.ServerRenderer.ServerRenderRegistry registry)\n")
                .Append(indent)
                .Append("    {\n")
                .Append(indent)
                .Append("        global::System.ArgumentNullException.ThrowIfNull(registry);\n");

            foreach (var registration in ordered)
            {
                if (registration.HasServerRender)
                {
                    builder.Append(indent).Append("        registry.Register(")
                        .Append(QualifiedTypeName(registration))
                        .Append(".__ViuServerRenderRegistration);\n");
                }
            }

            builder.Append(indent).Append("    }\n")
                .Append(indent).Append("}\n");
        }

        AppendLegacyCatalog(builder, indent, "GeneratedViuComponents", componentCatalogName, false);
        if (hasServerRenders)
        {
            AppendLegacyCatalog(builder, indent, "GeneratedViuServerRenders", serverCatalogName, true);
        }

        if (hasNamespace)
        {
            builder.Append("}\n");
        }

        if (autoRegister)
        {
            builder.Append("internal static class ViuGeneratedCatalogInitialization\n{\n")
                .Append("    [global::System.Runtime.CompilerServices.ModuleInitializer]\n")
                .Append("    internal static void Initialize()\n    {\n");
            AppendCatalogInitialization(builder, assemblyIdentity, catalogPrefix + componentCatalogName, false);
            if (ownsServerRenders)
            {
                AppendCatalogInitialization(builder, assemblyIdentity, catalogPrefix + serverCatalogName, true);
            }
            if (!references.IsDefaultOrEmpty)
            {
                foreach (GeneratedCatalogReference reference in references)
                {
                    AppendCatalogInitialization(builder, reference.Identity, reference.TypeName, reference.IsServer);
                }
            }
            builder.Append("    }\n}\n");
        }

        builder.Append(SingleFileComponentRenderGlue.Source);
        return builder.ToString();
    }

    private static string CatalogSuffix(string identity)
    {
        ulong hash = 14695981039346656037UL;
        int separator = identity.IndexOf(',');
        string assemblyName = separator < 0 ? identity : identity.Substring(0, separator);
        foreach (char character in assemblyName)
        {
            hash = unchecked((hash ^ character) * 1099511628211UL);
        }
        return hash.ToString("x16", System.Globalization.CultureInfo.InvariantCulture);
    }

    private static void AppendLegacyCatalog(StringBuilder builder, string indent, string name,
        string target, bool server)
    {
        string parameter = server ? "registry" : "factory";
        builder.Append(indent).Append("/// <summary>Explicit registration entry point for this assembly's generated catalog.</summary>\n")
            .Append(indent).Append("public static class ").Append(name).Append("\n")
            .Append(indent).Append("{\n")
            .Append(indent).Append("    /// <summary>Registers this assembly's generated definitions.</summary>\n")
            .Append(indent).Append("    /// <param name=\"").Append(parameter).Append("\">The application-owned registration target.</param>\n")
            .Append(indent).Append("    public static void Register(global::Assimalign.Viu.")
            .Append(server ? "ServerRenderer.ServerRenderRegistry" : "Components.ComponentFactory")
            .Append(' ').Append(parameter).Append(") => ").Append(target).Append(".Register(").Append(parameter).Append(");\n")
            .Append(indent).Append("}\n");
    }

    private static void AppendCatalogInitialization(StringBuilder builder, string identity, string typeName, bool server)
    {
        builder.Append("        global::Assimalign.Viu.")
            .Append(server ? "ServerRenderer.GeneratedServerRenderCatalogs" : "Components.GeneratedComponentCatalogs")
            .Append(".Register(")
            .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(identity, true))
            .Append(", ").Append(typeName).Append(".Register);\n");
    }

    private static string QualifiedTypeName(in GeneratedComponentRegistration registration)
        => registration.Namespace is null
            ? "global::" + registration.ClassName
            : "global::" + registration.Namespace + "." + registration.ClassName;
}
